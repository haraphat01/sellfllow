#!/usr/bin/env node
// Fallback generator for src/db/types/database.ts when `supabase gen types`
// is unavailable. Reads a JSON schema description (produced by
// scripts/db-types-local.sh) on stdin and emits the same shape as the Supabase
// CLI (Tables/Views/Functions/Enums with Row/Insert/Update).
// Prefer: npm run db:types (supabase gen types --linked).
import { readFileSync, writeFileSync } from "node:fs";

const input = JSON.parse(readFileSync(0, "utf8"));
const out = process.argv[2] ?? "src/db/types/database.ts";

const enums = input.enums ?? {};
const tsType = (udt, isArray) => {
  const base = udt.replace(/^_/, "");
  let t;
  if (enums[base]) t = `Database["public"]["Enums"]["${base}"]`;
  else if (["int2", "int4", "int8", "float4", "float8", "numeric", "bigint", "integer", "smallint"].includes(base)) t = "number";
  else if (base === "bool" || base === "boolean") t = "boolean";
  else if (["json", "jsonb"].includes(base)) t = "Json";
  else t = "string"; // uuid, text, citext, timestamptz, date, inet, bpchar, tsvector...
  return isArray || udt.startsWith("_") ? `${t}[]` : t;
};

const byTable = {};
for (const c of input.columns) (byTable[c.table] ??= []).push(c);

let s = `// AUTO-GENERATED by scripts/gen-db-types.mjs — do not edit by hand.
// Regenerate with \`npm run db:types\` (hosted) or \`npm run db:types:local\`.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;

for (const table of Object.keys(byTable).sort()) {
  const cols = byTable[table].sort((a, b) => a.pos - b.pos);
  const row = cols.map((c) => `          ${c.name}: ${tsType(c.udt)}${c.nullable ? " | null" : ""}`).join("\n");
  const ins = cols
    .filter((c) => !c.generated)
    .map((c) => {
      const optional = c.nullable || c.has_default;
      return `          ${c.name}${optional ? "?" : ""}: ${tsType(c.udt)}${c.nullable ? " | null" : ""}`;
    })
    .join("\n");
  const upd = cols
    .filter((c) => !c.generated)
    .map((c) => `          ${c.name}?: ${tsType(c.udt)}${c.nullable ? " | null" : ""}`)
    .join("\n");
  const rels = (input.fks ?? [])
    .filter((f) => f.table === table && f.ref_schema === "public")
    .map(
      (f) => `          {
            foreignKeyName: "${f.name}"
            columns: ["${f.column}"]
            isOneToOne: ${f.one_to_one}
            referencedRelation: "${f.ref_table}"
            referencedColumns: ["${f.ref_column}"]
          },`,
    )
    .join("\n");
  s += `      ${table}: {
        Row: {
${row}
        }
        Insert: {
${ins}
        }
        Update: {
${upd}
        }
        Relationships: [
${rels}
        ]
      }
`;
}

s += `    }
    Views: {
      [_ in never]: never
    }
    Functions: {
`;
for (const fn of input.functions ?? []) {
  const args = fn.args.length
    ? `{ ${fn.args.map((a) => `${a.name}${a.has_default ? "?" : ""}: ${tsType(a.udt)}`).join("; ")} }`
    : "never";
  s += `      ${fn.name}: { Args: ${args}; Returns: ${tsType(fn.returns)} }\n`;
}
s += `    }
    Enums: {
`;
for (const [name, values] of Object.entries(enums).sort()) {
  s += `      ${name}: ${values.map((v) => JSON.stringify(v)).join(" | ")}\n`;
}
s += `    }
    CompositeTypes: {
      [_ in never]: never
    }
  }
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

writeFileSync(out, s);
console.log(`wrote ${out}`);
